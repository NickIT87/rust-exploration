// Ищет `target` в отсортированном по возрастанию срезе.
// Возвращает индекс найденного элемента или `None`, если элемент отсутствует.

pub fn binary_search<T: Ord>(sorted: &[T], target: &T) -> Option<usize> {
    // Начинаем проверку с первого элемента среза.
    let mut left = 0;
    // Задаём правую границу диапазона; она не включается в поиск.
    let mut right = sorted.len();

    // Продолжаем, пока в диапазоне остаётся хотя бы один элемент.
    while left < right {
        // Находим середину диапазона, не складывая left и right напрямую.
        let middle = left + (right - left) / 2;

        // Сравниваем элемент в середине с искомым значением.
        match sorted[middle].cmp(target) {
            // Если середина меньше цели, продолжаем поиск справа от неё.
            std::cmp::Ordering::Less => left = middle + 1,
            // Если середина больше цели, исключаем её и всё справа.
            std::cmp::Ordering::Greater => right = middle,
            // Если значения равны, возвращаем индекс найденного элемента.
            std::cmp::Ordering::Equal => return Some(middle),
        }
    }

    // Возвращаем None, если диапазон закончился и цель не нашлась.
    None
}
